#!/usr/bin/env python3
"""Writes shared/brand-icons.ts from @lobehub/icons-static-svg (MIT).

Usage: npm pack @lobehub/icons-static-svg@<version>, unpack it, then
  python3 -I scripts/brand-icons.py <unpacked package dir> shared/brand-icons.ts
"""
